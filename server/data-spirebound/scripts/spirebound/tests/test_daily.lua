-- FLOOR1_REVIEW.md F1-60: a daily login streak (small, never power)
SpireTest.add("daily: the streak grows on consecutive days, resets after a gap, pays once a day", function()
	SpireTest.eq(SpireDaily.next(nil, nil, 100), 1, "first ever login: day 1")
	SpireTest.eq(SpireDaily.next(100, 1, 101), 2, "the next day: day 2")
	SpireTest.eq(SpireDaily.next(100, 3, 100), nil, "same day: nothing new")
	SpireTest.eq(SpireDaily.next(100, 5, 103), 1, "missed days: back to day 1")
	SpireTest.eq(SpireDaily.next(100, 7, 101), 1, "after day 7 the week starts again")
	SpireTest.eq(SpireDaily.reward(3).gold, 300, "day 3: 300 gold")
	SpireTest.eq(SpireDaily.reward(7).gold, 1000, "day 7: 1000 gold")
	SpireTest.eq(SpireDaily.reward(7).potions, 5, "day 7: five health potions")
end)

-- FLOOR1_REVIEW.md F1-63: an hourly lucky climber (chat moves, nobody is left out for long)
SpireTest.add("lucky: picks only real climbers, never the same one twice in a row, and pays by level", function()
	local list = { { name = "A", level = 5, staff = false }, { name = "B", level = 20, staff = false }, { name = "GM", level = 900, staff = true } }
	SpireTest.eq(SpireDaily.luckyPick(list, nil, 0.0), "B", "below level 8 doesn't count; staff never")
	SpireTest.eq(SpireDaily.luckyPick({ { name = "B", level = 20, staff = false } }, "B", 0.5), nil, "not the same one twice in a row")
	SpireTest.eq(SpireDaily.luckyGold(20), 400, "20 gold a level")
	SpireTest.eq(SpireDaily.luckyGold(500), 5000, "capped at 5000")
end)

-- P12: the tower's bounty on the strongest climber, and the Monument's leaderboards
SpireTest.add("daily: the tower's bounty only marks climbers in PvP range", function()
	local pick = SpireDaily.topBountyPick
	SpireTest.eq(pick({ { name = "A", level = 40 }, { name = "B", level = 49 } }), nil, "nobody below 50")
	SpireTest.eq(pick({ { name = "A", level = 80 }, { name = "B", level = 120 }, { name = "C", level = 300, staff = true } }), "B", "the highest non-staff")
	SpireTest.eq(SpireDaily.topBountyGold(120), 12000, "100 gold a level")
	SpireTest.eq(SpireDaily.topBountyGold(900), 50000, "capped")
	SpireTest.eq(SpireMonumentText():find("Top climbers") ~= nil, true, "the Monument shows the top climbers")
	local m = WorldPoints.monument
	local t = Tile(Position(m.x, m.y - 1, m.z))
	SpireTest.eq(t ~= nil and t:getTopDownItem() ~= nil or t:getTopTopItem() ~= nil or t:getItemCount() > 0, true, "the statue stands where the Monument is")
end)

