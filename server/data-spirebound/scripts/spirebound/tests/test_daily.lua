-- FLOOR1_REVIEW.md F1-60: a daily login streak (small, never power)
SpireTest.add("daily: the streak grows on consecutive days, resets after a gap, pays once a day", function()
	SpireTest.eq(SpireDaily.next(nil, nil, 100), 1, "first ever login: day 1")
	SpireTest.eq(SpireDaily.next(100, 1, 101), 2, "the next day: day 2")
	SpireTest.eq(SpireDaily.next(100, 3, 100), nil, "same day: nothing new")
	SpireTest.eq(SpireDaily.next(100, 5, 103), 1, "missed days: back to day 1")
	SpireTest.eq(SpireDaily.next(100, 7, 101), 1, "after day 7 the week starts again")
	SpireTest.eq(SpireDaily.reward(3).gold, 300, "day 3: 300 gold")
	SpireTest.eq(SpireDaily.reward(7).gold, 1000, "day 7: 1000 gold")
	SpireTest.eq(SpireDaily.reward(7).potions, 5, "day 7: five health potions")
end)
