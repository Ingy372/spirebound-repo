-- Roadmap R14: moderation basics.
SpireTest.add("moderation: the chat filter blocks the worst words in three languages, look-alikes too", function()
	SpireTest.eq((SpireMod.blocked("hello there, want to hunt?")), false, "a normal line passes")
	SpireTest.eq((SpireMod.blocked("you FUCKING noob")), true, "English, any case")
	SpireTest.eq((SpireMod.blocked("vai tomar no cu, caralho")), true, "Portuguese")
	SpireTest.eq((SpireMod.blocked("eres un pendejo")), true, "Spanish")
	SpireTest.eq((SpireMod.blocked("f4gg0t")), true, "digits for letters")
	SpireTest.eq((SpireMod.blocked("Scunthorpe classic")), false, "whole words only")
end)

SpireTest.add("moderation: reports, the GM log, the rules and the punishment ladder", function()
	local name, what = SpireMod.parseReport("Bad Guy, kept blocking the cave")
	SpireTest.eq(name, "Bad Guy", "report: the name")
	SpireTest.eq(what, "kept blocking the cave", "report: what happened")
	SpireTest.eq(SpireMod.parseReport("just a name"), nil, "a report needs what happened")
	local before = #SpireMod.reports()
	SpireMod.addReport("Tester", "Bad Guy", "testing the report box")
	SpireTest.eq(#SpireMod.reports(), before + 1, "a report is kept for the GMs")
	SpireMod.log("TestGM", "muted", "Bad Guy", "60 minutes")
	local last = SpireMod.recentLog(1)[1]
	SpireTest.eq(last and last.action, "muted", "GM actions are logged")
	SpireTest.eq(#SpireMod.LADDER, 5, "the punishment ladder has five steps")
	SpireTest.eq(SpireMod.rulesText():find("!report") ~= nil, true, "the rules tell players how to report")
	local list = SpireMod.reports()
	table.remove(list)
	kv.scoped("spirebound-reports"):set("open", list)
end)
