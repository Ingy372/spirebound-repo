#!/usr/bin/env python3
"""Where every Floor 1 material drops (gear progression spec 4.10; Jay's playtest 2026-11-23: "they hear they need
'venomous slime' but have no idea how to get it or where the monster is located").

Writes, from the monster loot tables and the Floor 1 ground plan:
  data/item_descriptions.json                       item id -> "Dropped by Hopper Toads (Toad Pond, ...)." (the item's look text)
  server/data-spirebound/lib/spirebound/material_sources.lua   the same for the crafters' replies
Run: python tools/gen_material_sources.py   (tools/check_materials.py checks the result)
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path[:0] = [str(ROOT / "tools"), str(ROOT / "maps")]

# Junk items players already recognise (weapons, armour, food): no "dropped by" text needed
NOT_MATERIAL = {3274, 3286, 3294, 3350, 3352, 3359, 3361, 3577, 3582, 3607}


def plural(name):
    if name.endswith("Wolf"):
        return name[:-1] + "ves"
    return name + "s"


def sources():
    from gen_monsters import MONSTERS, GOLD, PLAT
    from junk_prices import JUNK
    from floor1_plan import CAMPS
    grounds = {}
    for c in CAMPS:
        for m in {x[0] for x in c.get("mix", [])}:
            grounds.setdefault(m, []).append(c["title"])
    text = (ROOT / "server/data-spirebound/lib/spirebound/crafting.lua").read_text(encoding="utf-8")
    needs = {int(x) for blk in re.findall(r"needs = \{ ((?:\{ \d+, \d+ \},? ?)+) \}", text) for x in re.findall(r"\{ (\d+), \d+ \}", blk)}
    wanted = (needs | {iid for _n, iid, _p in JUNK}) - NOT_MATERIAL
    droppers = {}
    for name, d in MONSTERS.items():
        if name not in grounds:
            continue
        for iid, chance, _m in d.get("loot", []):
            if iid in wanted and iid not in (GOLD, PLAT):
                droppers.setdefault(iid, []).append((chance, name))
    out = {}
    for iid, lst in droppers.items():
        lst.sort(reverse=True)
        parts = [f"{plural(name)} ({', '.join(grounds[name][:2])})" for _c, name in lst[:2]]
        out[iid] = "Dropped by " + " and ".join(parts) + "."
    return out, needs


def main():
    out, _needs = sources()
    (ROOT / "data/item_descriptions.json").write_text(json.dumps({str(k): v for k, v in sorted(out.items())}, indent=1) + "\n", encoding="utf-8")
    L = ["-- GENERATED by tools/gen_material_sources.py: where each Floor 1 material drops. Do not edit by hand.",
         "SpireMaterials = { where = {"]
    for iid, v in sorted(out.items()):
        L.append(f'\t[{iid}] = "{v}",')
    L.append("} }")
    (ROOT / "server/data-spirebound/lib/spirebound/material_sources.lua").write_text("\n".join(L) + "\n", encoding="utf-8")
    print(f"wrote data/item_descriptions.json and material_sources.lua: {len(out)} materials")


if __name__ == "__main__":
    main()
