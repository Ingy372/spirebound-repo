#!/usr/bin/env python3
"""Writes the Floor 1 quest-giver NPC files that follow the shared quest dialogue (lib/spirebound/quests.lua).
Miller Agna and Captain Dorrow (older, hand-written) use the same pattern. Usage: python3 tools/gen_quest_npcs.py"""
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "server" / "data-spirebound" / "npc"

NPCS = {
    "quest_brannoch": dict(name="Hunter Brannoch", desc="a hunter of the Hunters' Hall", look=(129, 78, 95, 116, 115, 0),
                           greet="Brannoch, of the Hunters' Hall. Ask me about a {quest}, {report} when one is done, or where to {hunt}."),
    "quest_corwin": dict(name="Fisher Corwin", desc="a fisher of the river bank", look=(128, 38, 96, 97, 115, 0),
                         greet="Corwin. I fish the river and the marsh. Ask me about a {quest}, {report} when you have finished, or where to {hunt}."),
}

TEMPLATE = '''-- GENERATED by tools/gen_quest_npcs.py. Quest giver (lib/spirebound/quests.lua).
local npcName = "{name}"
local npcType = Game.createNpcType(npcName)
local npcConfig = {{}}
npcConfig.name = npcName
npcConfig.description = "{desc}"
npcConfig.health = 100
npcConfig.maxHealth = npcConfig.health
npcConfig.walkInterval = 0
npcConfig.walkRadius = 0
npcConfig.outfit = {{ lookType = {l0}, lookHead = {l1}, lookBody = {l2}, lookLegs = {l3}, lookFeet = {l4}, lookAddons = {l5} }}
npcConfig.flags = {{ floorchange = false }}

local keywordHandler = KeywordHandler:new()
local npcHandler = NpcHandler:new(keywordHandler)
npcType.onThink = function(npc, interval) npcHandler:onThink(npc, interval) end
npcType.onAppear = function(npc, creature) npcHandler:onAppear(npc, creature) end
npcType.onDisappear = function(npc, creature) npcHandler:onDisappear(npc, creature) end
npcType.onMove = function(npc, creature, from, to) npcHandler:onMove(npc, creature, from, to) end
npcType.onSay = function(npc, creature, type, message) npcHandler:onSay(npc, creature, type, message) end
npcType.onCloseChannel = function(npc, player) npcHandler:onCloseChannel(npc, player) end

local function creatureSayCallback(npc, player, type, msg)
	if not npcHandler:checkInteraction(npc, player) then
		return false
	end
	if SpireHunt and MsgContains(msg, "hunt") then
		npcHandler:say(SpireHunt.advice(player:getLevel()), npc, player)
		return true
	end
	SpireQuests.talk(npc, npcHandler, player, msg, npcName)
	return true
end

npcHandler:setMessage(MESSAGE_GREET, "{greet}")
npcHandler:setMessage(MESSAGE_FAREWELL, "Safe travels.")
npcHandler:setCallback(CALLBACK_MESSAGE_DEFAULT, creatureSayCallback)
npcHandler:addModule(FocusModule:new(), npcConfig.name, true, true, true)
npcType:register(npcConfig)
'''

for fname, d in NPCS.items():
    look = list(d["look"]) + [0] * (6 - len(d["look"]))
    text = TEMPLATE.format(name=d["name"], desc=d["desc"], greet=d["greet"], l0=look[0], l1=look[1], l2=look[2], l3=look[3], l4=look[4], l5=look[5])
    (OUT / f"{fname}.lua").write_text(text, encoding="utf-8", newline="\n")
print(f"wrote {len(NPCS)} quest NPCs")
