#!/usr/bin/env python3
"""The Spirebound gear ladder for Floors 1-2 (roadmap R12, REVIEW 2.1-2.4): one table, original names.

Each vocation gets three pieces per floor: a rare DROP from the floor's harder monsters, a QUEST piece from the floor's
hand-written quest line, and the BOSS piece (the floor's best), which the floor boss drops for its top fighter.
Every piece is a base Tibia item with its own name and a small bonus. Run: python tools/gen_gear.py
(writes server/data-spirebound/lib/spirebound/gear.lua; tools/check_names.py checks the names).
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
VANGUARD, RANGER, ARCANIST, MYSTIC = 4, 3, 1, 2

# (vocation, floor, source, base item id, name, bonus kind, bonus)
GEAR = [
    # ---- Floor 1 (levels 1-35)
    (VANGUARD, 1, "drop", 3273, "Briarguard Sabre", "attack", 2),
    (VANGUARD, 1, "quest", 3359, "Hearthward Mail", "armor", 2),
    (VANGUARD, 1, "boss", 3303, "Stairlord's Cleaver", "attack", 4),
    (RANGER, 1, "drop", 3350, "Copsewood Bow", "attack", 1),
    (RANGER, 1, "quest", 3372, "Trailwarden Greaves", "armor", 2),
    (RANGER, 1, "boss", 3349, "Stair-Iron Crossbow", "attack", 3),
    (ARCANIST, 1, "drop", 3074, "Wand of Hearth Sparks", "attack", 3),
    (ARCANIST, 1, "quest", 3361, "Millward Mantle", "armor", 3),
    (ARCANIST, 1, "boss", 3072, "Wand of the Long Stair", "attack", 5),
    (MYSTIC, 1, "drop", 3066, "Reedroot Rod", "attack", 3),
    (MYSTIC, 1, "quest", 3361, "Thornward Robe", "armor", 3),
    (MYSTIC, 1, "boss", 3070, "Rod of the Long Stair", "attack", 5),
    # ---- Floor 2 (levels 35-60)
    (VANGUARD, 2, "drop", 3271, "Highland Edge", "attack", 3),
    (VANGUARD, 2, "quest", 3357, "Hornbreaker Plate", "armor", 2),
    (VANGUARD, 2, "boss", 3280, "Aurochs-Crown Blade", "attack", 4),
    (RANGER, 2, "drop", 3350, "Ridgecat Longbow", "attack", 3),
    (RANGER, 2, "quest", 3362, "Strider Leggings", "armor", 2),
    (RANGER, 2, "boss", 3349, "Crowned Arbalest", "attack", 6),
    (ARCANIST, 2, "drop", 3073, "Wand of Dust Storms", "attack", 3),
    (ARCANIST, 2, "quest", 3378, "Mesa-Weave Coat", "armor", 2),
    (ARCANIST, 2, "boss", 3068, "Wand of the Crowned Herd", "attack", 6),
    (MYSTIC, 2, "drop", 3067, "Highwind Rod", "attack", 3),
    (MYSTIC, 2, "quest", 3378, "Grazer-Hide Coat", "armor", 2),
    (MYSTIC, 2, "boss", 3065, "Rod of the Crowned Herd", "attack", 6),
]
DROP_FROM = {1: ["Bandit Captain", "Grey Alpha", "Ruin Sentinel", "Stonehorn Ram"],
             2: ["Herd Bull", "Stonehide Bull", "Mesa Wyrmling"]}
DROP_CHANCE = 0.03          # per kill of those monsters: one piece of that floor, for a random vocation
BOSSES = {1: "Axe-Lord of the Stair", 2: "Crowned Aurochs"}


def main():
    L = ["-- GENERATED by tools/gen_gear.py (roadmap R12). Do not edit by hand.",
         "-- The gear ladder: per vocation and floor a rare drop, a quest piece and the boss piece (the floor's best).",
         "SpireGear = SpireGear or {}", "SpireGear.list = {"]
    for voc, floor, src, base, name, kind, bonus in GEAR:
        L.append(f'\t{{ vocation = {voc}, floor = {floor}, source = "{src}", base = {base}, name = "{name}", kind = "{kind}", bonus = {bonus} }},')
    L.append("}")
    L.append("SpireGear.dropFrom = {")
    for floor, mons in DROP_FROM.items():
        L.append(f"\t[{floor}] = {{ " + ", ".join(f'"{m}"' for m in mons) + " },")
    L.append("}")
    L.append(f"SpireGear.DROP_CHANCE = {DROP_CHANCE}")
    L.append("SpireGear.bosses = { " + ", ".join(f'[{f}] = "{b}"' for f, b in BOSSES.items()) + " }")
    out = ROOT / "server/data-spirebound/lib/spirebound/gear.lua"
    out.write_text("\n".join(L) + "\n", encoding="utf-8")
    print(f"wrote {out.name}: {len(GEAR)} pieces")


if __name__ == "__main__":
    main()
