#!/usr/bin/env python3
"""Waycrystals (Jay's idea, 2026-11-26, Q94; rules DESIGN.md 3.7 and Q95): one crystal per floor, each its own colour.
Use one to go to that floor's town, or (menu) to the gate of one of its hunting grounds your level has reached.

The one list of crystals. Read by tools/gen_gear.py (item names), tools/gen_npcs.py (the Runewright sells Floor 1's)
and tools/balance.py (prices from each floor's hunting income; writes lib/spirebound/crystals_data.lua).

The item ids are placeholder pictures from the base game until the icons in ART_REQUESTS.md are drawn.
"""
import csv
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

# floor -> (colour, item id of the placeholder picture). "Teleport Crystal" is SAO's item name: ours are Waycrystals.
CRYSTALS = {
    1: ("Amber", 3251), 2: ("Verdant", 11454), 3: ("Azure", 9240), 4: ("Violet", 5944), 5: ("Crimson", 8225),
    6: ("Cyan", 9102), 7: ("Rose", 9697), 8: ("Frost", 942), 9: ("Onyx", 9237), 10: ("Cerulean", 7281),
}
MINUTES = 4            # a crystal costs about this many minutes of the floor's hunting income (there and back: 8)
MIN_PRICE = 50
CAST_SECONDS = 3       # standing still before it works (moving or being hurt cancels it)
FIGHT_LOCK = 10        # seconds after any hit given or taken
TOWN_POINT = {1: "temple_hearthgate"}   # floor n's town otherwise: WorldPoints["f<n>_temple"]


def name(n):
    return f"{CRYSTALS[n][0]} Waycrystal (Floor {n})"


def plural(n):
    return f"{CRYSTALS[n][0]} Waycrystals (Floor {n})"


def description(n):
    town = "Hearthgate" if n == 1 else f"Floor {n}'s town"
    return (f"Hold it still for {CAST_SECONDS} seconds to travel to {town}, or to the gate of a Floor {n} hunting ground "
            "you have the level for. Used up on arrival. Not in a fight, a boss room or a party cave.")


def renames():
    return {str(iid): dict(name=name(n).lower(), plural=plural(n).lower(), description=description(n))
            for n, (_c, iid) in CRYSTALS.items()}


def floor_gold_h():
    """Each floor's modelled hunting income (data/balance_floors.csv, written by tools/balance.py)."""
    f = ROOT / "data" / "balance_floors.csv"
    if not f.exists():
        return {}
    return {int(r["floor"]): int(r["gold_h"]) for r in csv.DictReader(open(f))}


def price(n, gold_h=None):
    g = (gold_h or floor_gold_h()).get(n)
    if not g:
        return 300                                   # the old temple scroll's price until the balance table exists
    return max(MIN_PRICE, int(round(g * MINUTES / 60 / 10)) * 10)


def floor1_grounds():
    """Floor 1's hunting grounds with the gate a player arrives at (maps/hunt_routes.json, made by tools/mapgen.py)
    and their level band (maps/floor1_plan.py)."""
    import sys
    sys.path.insert(0, str(ROOT / "maps"))
    from floor1_plan import CAMPS, APEX
    routes = json.loads((ROOT / "maps" / "hunt_routes.json").read_text(encoding="utf-8"))
    out = []
    for c in list(CAMPS) + [APEX]:
        r = routes.get(c["id"])
        if r:
            out.append(dict(id=c["id"], title=c["title"], lo=c["levels"][0], hi=c["levels"][1], gate=r["gate"]))
    return sorted(out, key=lambda g: (g["lo"], g["title"]))


def lua(gold_h):
    """lib/spirebound/crystals_data.lua"""
    L = ["-- GENERATED by tools/balance.py from tools/crystals.py (Waycrystals, DESIGN.md 3.7). Do not edit by hand.",
         "SpireCrystalData = {", f"\tCAST_SECONDS = {CAST_SECONDS}, FIGHT_LOCK = {FIGHT_LOCK},", "\tbyItem = {"]
    for n, (colour, iid) in CRYSTALS.items():
        town = TOWN_POINT.get(n, f"f{n}_temple")
        L.append(f'\t\t[{iid}] = {{ floor = {n}, colour = "{colour}", name = "{name(n)}", price = {price(n, gold_h)}, town = "{town}" }},')
    L.append("\t},")
    L.append("\tgrounds = {")
    L.append("\t\t[1] = {")
    for g in floor1_grounds():
        x, y, z = g["gate"]
        L.append(f'\t\t\t{{ id = "{g["id"]}", title = "{g["title"]}", lo = {g["lo"]}, hi = {g["hi"]}, pos = {{ {x}, {y}, {z} }} }},')
    L.append("\t\t},")
    L.append("\t},")
    L.append("}")
    return "\n".join(L) + "\n"


if __name__ == "__main__":
    g = floor_gold_h()
    for n in CRYSTALS:
        print(n, name(n), price(n, g))
